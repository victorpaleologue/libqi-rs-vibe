/// The type of the node through which a module reaches the space of its host.
pub type SpaceNode = crate::Node<crate::service_directory::Client>;

/// The URL of the space a module connects to when its host gives none: the `QI_URL` environment
/// variable, as `libqi` reads it, else the local NAOqi.
pub const DEFAULT_SPACE_URL: &str = "tcp://127.0.0.1:9559";

/// Conversion of the values factories return into objects.
///
/// Implemented for every [`Object`] (the adapters generated by [`#[qi::object]`](macro@crate::object),
/// dynamic objects, [`AnyObject`]...).
pub trait IntoAnyObject {
    fn into_any_object(self) -> AnyObject;
}

impl<O> IntoAnyObject for O
where
    O: Object + 'static,
{
    fn into_any_object(self) -> AnyObject {
        AnyObject::new(self)
    }
}

/// The URL of the space to connect to when none is given: `QI_URL`, else [`DEFAULT_SPACE_URL`].
pub fn default_space_url() -> String {
    std::env::var("QI_URL")
        .ok()
        .filter(|url| !url.is_empty())
        .unwrap_or_else(|| DEFAULT_SPACE_URL.to_owned())
}
