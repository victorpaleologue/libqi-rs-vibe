//! Modules: shared libraries of objects and functions, loaded by the processes of a space.
//!
//! A `qi` *module* is a shared library that exports functions and object factories under a
//! name, like the C++ modules of `libqi` (`QI_REGISTER_MODULE`). A process loads it and uses its
//! members: `qilaunch -o module.Factory` registers the object a factory creates as a service,
//! `qilaunch -f module.function` calls a function, and NAOqi loads the libraries listed in its
//! `autoload.ini`.
//!
//! A module is written in Rust by applying [`#[qi::module]`](macro@crate::module) to a `mod` of a
//! crate built as a `cdylib`:
//!
//! ```ignore
//! #[qi::module]
//! pub mod greetings {
//!     use qi::module::Session;
//!
//!     /// A function of the module: `qilaunch -n demo -f 'greetings.hello("Rust")'`.
//!     pub fn hello(name: String) -> qi::Result<String> {
//!         Ok(format!("Hello, {name}!"))
//!     }
//!
//!     /// A factory of the module: `qilaunch -n demo -o greetings.Greeter` registers its object
//!     /// as the service `Greeter`, and so does NAOqi when it loads the library (`autoload`).
//!     #[qi::factory(autoload)]
//!     pub async fn greeter(session: Session) -> qi::Result<GreeterObject<MyGreeter>> {
//!         Ok(GreeterObject::new(MyGreeter::new(session)))
//!     }
//! }
//! ```
//!
//! # How a module is loaded
//!
//! The library carries its own copy of this crate and runs it on its own threads: the members
//! of the module are Rust objects, served by the library to the process that loads it through a
//! *private space* hosted on the loopback interface (`tcp://127.0.0.1`, ephemeral port). The
//! loading process connects to that space and obtains the module as an object, whose methods are
//! the functions and factories of the module; the objects factories create are proxies to the
//! Rust objects, which the loading process registers as services of its own space. This keeps
//! the interface between the library and its host free of any Rust or C++ type: hosts written
//! with this crate (`qi-launch`), with the C++ `libqi` (`qilaunch`, NAOqi), or loading the library
//! the way NAOqi loads its modules all go through it. See the [`abi`] module for the entry
//! points of the library.
//!
//! Members that need to reach the space take a [`Session`] as first parameter: a handle to a
//! node of the space the host belongs to, connected on first use.

